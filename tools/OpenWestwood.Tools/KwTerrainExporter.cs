using System.Text;
using System.Xml.Linq;
using OpenWestwood.Formats.Maps;

namespace OpenWestwood.Tools;

/// <summary>
/// Kane's Wrath's terrain textures (mods/zh/rules/kw/terrain-types.yaml): which picture each texture name in a map's
/// tile data shows (e.g. CityRubble06 is Terrain/TRock_Rubble06.tga).
///
/// Kane's Wrath keeps no table of these. Its map editor writes each map's texture names into the .map, and the
/// pictures it used into the map's map.xml (TerrainTextureAtlas tiles: the picture and a TextureID, a hash of the
/// name). The hash isn't known here, so the pairs are worked out from EA's maps: in every map the names and the
/// TextureIDs are the same set, so a name's ID is the one every map using it has, and IDs already taken by other
/// names are crossed off. When a few IDs are left (names that always appear together), the picture whose file name
/// is closest to the texture name is chosen.
/// </summary>
public static class KwTerrainExporter
{
    public static void Run(string root, string output)
    {
        string mapsDir = Path.Combine(root, "content", "kaneswrath", "sdk", "Xml", "Maps");
        if (!Directory.Exists(mapsDir))
            return;
        var maps = new List<(HashSet<string> Names, HashSet<uint> Ids)>();
        var pictureOf = new Dictionary<uint, string>();
        foreach (string dir in Directory.GetDirectories(mapsDir).SelectMany(Directory.GetDirectories))
        {
            string xml = Path.Combine(dir, "map.xml");
            string? mapPath = Directory.GetFiles(dir, "*.map").FirstOrDefault();
            if (!File.Exists(xml) || mapPath == null)
                continue;
            var tiles = XDocument.Load(xml).Descendants().Where(e => e.Name.LocalName == "Tile" && e.Parent?.Name.LocalName == "TerrainTextureAtlas")
                .Select(e => (Picture: (string?)e.Attribute("BaseTexture"), Id: (string?)e.Attribute("TextureID")))
                .Where(t => t.Picture != null && uint.TryParse(t.Id, out _)).ToList();
            if (tiles.Count == 0)
                continue;
            HashSet<string> names;
            try
            {
                names = MapFile.Read(File.ReadAllBytes(mapPath)).BlendTiles?.TextureClasses.Select(c => c.Name).ToHashSet(StringComparer.OrdinalIgnoreCase) ?? [];
            }
            catch (Exception)
            {
                continue; // an editor test map in an older format
            }
            if (names.Count == 0)
                continue;
            foreach (var t in tiles)
                pictureOf[uint.Parse(t.Id!)] = t.Picture!;
            maps.Add((names, tiles.Select(t => uint.Parse(t.Id!)).ToHashSet()));
        }

        // Each name's possible IDs: those every map using the name has.
        var candidates = new Dictionary<string, HashSet<uint>>(StringComparer.OrdinalIgnoreCase);
        foreach (var (names, ids) in maps)
            foreach (string name in names)
                if (candidates.TryGetValue(name, out var c))
                    c.IntersectWith(ids);
                else
                    candidates[name] = new HashSet<uint>(ids);
        bool changed = true;
        while (changed)
        {
            changed = false;
            var taken = candidates.Values.Where(c => c.Count == 1).Select(c => c.First()).ToHashSet();
            foreach (var c in candidates.Values.Where(c => c.Count > 1))
                if (c.RemoveWhere(taken.Contains) > 0)
                    changed = true;
            // Names left with the same few IDs (they always appear together): the closest file name wins, closest pair first.
            if (!changed)
            {
                var pick = candidates.Where(kv => kv.Value.Count > 1)
                    .SelectMany(kv => kv.Value.Where(id => !taken.Contains(id)).Select(id => (Name: kv.Key, Id: id, Cost: Distance(NameKey(kv.Key), FileKey(pictureOf[id])))))
                    .OrderBy(p => p.Cost).ThenBy(p => p.Name, StringComparer.Ordinal).FirstOrDefault();
                if (pick.Name != null)
                {
                    candidates[pick.Name].Clear();
                    candidates[pick.Name].Add(pick.Id);
                    changed = true;
                }
            }
        }

        var sb = new StringBuilder("# GENERATED by 'OpenWestwood.Tools export-kw-factions' from Kane's Wrath's maps (content/kaneswrath/sdk/Xml/Maps).\n");
        sb.Append("# Kane's Wrath's terrain textures: the picture for each texture name in its maps (Terrain.big's art/terrain).\nTerrainTypes:\n");
        int count = 0;
        foreach (var (name, c) in candidates.OrderBy(kv => kv.Key, StringComparer.OrdinalIgnoreCase))
        {
            if (c.Count != 1 || !pictureOf.TryGetValue(c.First(), out var picture))
                continue;
            sb.Append($"  {name}:\n    Texture: {Path.GetFileName(picture.Replace('\\', '/'))}\n    Class: KANESWRATH\n");
            count++;
        }
        File.WriteAllText(Path.Combine(output, "terrain-types.yaml"), sb.ToString());
        Console.WriteLine($"Kane's Wrath terrain: {count} of {candidates.Count} texture names matched to pictures (from {maps.Count} maps).");
        WriteTiberium(Path.Combine(root, "content", "kaneswrath", "sdk", "Xml", "Tiberium"), output);
        WriteRoads(Path.Combine(root, "content", "kaneswrath", "sdk", "Xml", "GlobalData", "Roads.xml"), output);
        WriteRain(Path.Combine(root, "content", "kaneswrath", "sdk", "Xml", "GlobalData", "Weather.xml"), output);
    }

    /// <summary>rain.yaml: Kane's Wrath's rain (its Weather's Rain settings), for OpenWESTWOOD's RainRenderer.</summary>
    static void WriteRain(string file, string output)
    {
        if (!File.Exists(file) || XDocument.Load(file).Descendants().FirstOrDefault(e => e.Name.LocalName == "Rain") is not { } rain)
            return;
        var sb = new StringBuilder("# GENERATED by 'OpenWestwood.Tools export-kw-factions' from Kane's Wrath's weather (content/kaneswrath/sdk/Xml/GlobalData/Weather.xml).\nRain:\n");
        foreach (var a in rain.Attributes())
            if (a.Name.LocalName != "IsRaining")
                sb.Append($"  {a.Name.LocalName}: {(a.Name.LocalName == "RainTexture" ? "kw/" + a.Value.Trim() : a.Value.Trim())}\n");
        File.WriteAllText(Path.Combine(output, "rain.yaml"), sb.ToString());
    }

    /// <summary>
    /// roads.yaml: Kane's Wrath's road types (GlobalData/Roads.xml) as KW_&lt;id&gt; (the names KwMaps gives its maps'
    /// road points): their texture (in its art streams, "kw/&lt;name&gt;.dds"), width and the share of the texture
    /// the road fills.
    /// </summary>
    static void WriteRoads(string file, string output)
    {
        if (!File.Exists(file))
            return;
        var sb = new StringBuilder("# GENERATED by 'OpenWestwood.Tools export-kw-factions' from Kane's Wrath's roads (content/kaneswrath/sdk/Xml/GlobalData/Roads.xml).\nRoads:\n");
        foreach (var road in XDocument.Load(file).Descendants().Where(e => e.Name.LocalName == "Road"))
        {
            if ((string?)road.Attribute("id") is not { Length: > 0 } id || (string?)road.Attribute("Texture") is not { Length: > 0 } texture)
                continue;
            sb.Append($"  KW_{id}:\n    Texture: kw/{texture}.dds\n    RoadWidth: {(string?)road.Attribute("RoadWidth") ?? "35"}\n");
            sb.Append($"    RoadWidthInTexture: {(string?)road.Attribute("RoadWidthInTexture") ?? "1"}\n");
        }
        File.WriteAllText(Path.Combine(output, "roads.yaml"), sb.ToString());
    }

    /// <summary>
    /// tiberium.yaml: the crystals Kane's Wrath's Tiberium fields grow (each field's TiberiumField ThingToSpawn), as
    /// supply piles harvesters take boxes from. A map's fields are spread into crystals when it loads (KwMaps).
    /// </summary>
    static void WriteTiberium(string dir, string output)
    {
        if (!Directory.Exists(dir))
            return;
        XElement? Object(string file) => File.Exists(Path.Combine(dir, file))
            ? XDocument.Load(Path.Combine(dir, file)).Descendants().FirstOrDefault(e => e.Name.LocalName == "GameObject") : null;
        static string? Attr(XElement? e, string name) => (string?)e?.Attribute(name);
        static XElement? Find(XElement? e, string name) => e?.Descendants().FirstOrDefault(d => d.Name.LocalName == name);
        var sb = new StringBuilder("# GENERATED by 'OpenWestwood.Tools export-kw-factions' from Kane's Wrath's Tiberium (content/kaneswrath/sdk/Xml/Tiberium).\nObjects:\n");
        var crystals = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (string file in new[] { "TiberiumField.xml", "TiberiumFieldBlue.xml", "TiberiumFieldRedZone.xml" })
        {
            var o = Object(file);
            var field = Find(o, "TiberiumField");
            if (o == null || field == null)
                continue;
            string crystal = Attr(field, "ThingToSpawn") ?? "TiberiumCrystal";
            crystals.Add(crystal);
        }
        foreach (string crystal in crystals)
        {
            var o = Object(crystal + ".xml");
            if (o == null)
                continue;
            string model = Attr(Find(o, "Model"), "Name") ?? "TibCell01";
            // A crystal's worth (TiberiumCrystal NumBoxes x ValuePerBox: 50 x 7) in Zero Hour's 75-credit boxes.
            var behaviour = Find(Find(o, "Behaviors"), "TiberiumCrystal");
            int value = int.Parse(Attr(behaviour, "NumBoxes") ?? "50") * int.Parse(Attr(behaviour, "ValuePerBox") ?? "7");
            int boxes = Math.Max(1, (int)MathF.Round(value / 75f));
            var geometry = Find(Find(o, "Geometry"), "Shape");
            string radius = Attr(geometry, "MajorRadius") ?? "22", height = Attr(geometry, "Height") ?? "18";
            sb.Append($"  KW_{crystal}:\n    DisplayName: Tiberium\n    EditorSorting: MISC_NATURAL\n    KindOf: IMMOBILE SUPPLY_SOURCE STRUCTURE TD_OBJECT\n");
            sb.Append($"    Geometry: CYLINDER\n    GeometryMajorRadius: {radius}\n    GeometryMinorRadius: {radius}\n    GeometryHeight: {height}\n    GeometryIsSmall: Yes\n");
            sb.Append("    ArmorSet:\n      Conditions: None\n      Armor: InvulnerableAllArmor\n    Modules:\n");
            sb.Append($"      ModuleTag_01:\n        Module: Draw\n        Class: W3DModelDraw\n        DefaultConditionState:\n          Model: KW_{model}\n");
            sb.Append("      ModuleTag_02:\n        Module: Body\n        Class: ActiveBody\n        MaxHealth: 1.0\n        InitialHealth: 1.0\n");
            sb.Append("      ModuleTag_03:\n        Module: Behavior\n        Class: SupplyWarehouseCreate\n");
            sb.Append($"      ModuleTag_04:\n        Module: Behavior\n        Class: SupplyWarehouseDockUpdate\n        StartingBoxes: {boxes}\n        DeleteWhenEmpty: Yes\n        AllowsPassthrough: Yes\n        NumberApproachPositions: -1\n");
        }
        File.WriteAllText(Path.Combine(output, "tiberium.yaml"), sb.ToString());
    }

    /// <summary>A texture name in the files' words: "CityRubble06" as "rockrubble06", "PavementPlaza02" as "paveplaza02".</summary>
    static string NameKey(string name)
    {
        string s = new(name.ToLowerInvariant().Where(char.IsLetterOrDigit).ToArray());
        foreach (var (word, file) in new[] { ("city", "rock"), ("pavement", "pave") })
            if (s.StartsWith(word))
                return file + s[word.Length..];
        return s;
    }

    /// <summary>A picture's file name the same way: "ART:Terrain/TClif_Africa01.tga" as "cliffafrica01".</summary>
    static string FileKey(string path)
    {
        string s = new(Path.GetFileNameWithoutExtension(path.Replace('\\', '/')).ToLowerInvariant().Where(char.IsLetterOrDigit).ToArray());
        if (s.StartsWith('t'))
            s = s[1..];
        foreach (var (word, full) in new[] { ("clif", "cliff"), ("gras", "grass") })
            if (s.StartsWith(word) && !s.StartsWith(full))
                return full + s[word.Length..];
        return s;
    }

    static int Distance(string a, string b)
    {
        var d = new int[b.Length + 1];
        for (int j = 0; j <= b.Length; j++)
            d[j] = j;
        for (int i = 1; i <= a.Length; i++)
        {
            int prev = d[0];
            d[0] = i;
            for (int j = 1; j <= b.Length; j++)
            {
                int t = d[j];
                d[j] = Math.Min(Math.Min(d[j] + 1, d[j - 1] + 1), prev + (a[i - 1] == b[j - 1] ? 0 : 1));
                prev = t;
            }
        }
        return d[b.Length];
    }
}
